export const ARUCO_INNER_CELLS = 4                          // 4×4 사전
export const ARUCO_MARKER_CELLS = ARUCO_INNER_CELLS + 2     // 검정 테두리 한 칸씩 포함 6×6

/** 마커 번호 → 6×6 칸. 바깥 한 줄은 검정 테두리.
 *  [입력] arucoMarkerId: 0~249
 *  [출력] boolean[][]: [행][열], true=검정 (범위 밖이면 Error)
 */
export function arucoMarkerCells(arucoMarkerId: number): boolean[][] {
  const innerBits = DICT_4X4_250_INNER_BITS[arucoMarkerId]
  if (innerBits === undefined || !Number.isInteger(arucoMarkerId)) {
    throw new Error(`ArUco DICT_4X4_250 marker id must be 0..${RECEIPT_MARKER_ID_MAX}: ${arucoMarkerId}`)
  }
  return Array.from({ length: ARUCO_MARKER_CELLS }, (_, row) =>
    Array.from({ length: ARUCO_MARKER_CELLS }, (_, column) => {
      const isBorder = row === 0 || column === 0 || row === ARUCO_MARKER_CELLS - 1 || column === ARUCO_MARKER_CELLS - 1
      if (isBorder) return true
      const bitIndex = (row - 1) * ARUCO_INNER_CELLS + (column - 1)
      const isWhite = (innerBits >> (ARUCO_INNER_CELLS * ARUCO_INNER_CELLS - 1 - bitIndex)) & 1
      return !isWhite
    }),
  )
}
